-- Factory Store database and private bill storage setup.
-- Run once in Supabase SQL Editor.

create table if not exists public.material_entries (
    id bigint generated by default as identity primary key,
    entry_date date not null,
    entry_time text not null,
    material_name text not null,
    quantity numeric(14,3) not null check (quantity > 0),
    unit text not null,
    vendor_name text not null,
    vendor_address text,
    store_name text,
    brought_by text,
    received_by text,
    through text,
    unit_price numeric(14,2) not null default 0,
    total_price numeric(14,2) not null default 0,
    bill_code text,
    bill_path text,
    notes text,
    created_at timestamptz not null default now()
);

alter table public.material_entries enable row level security;

-- Only logged-in staff can read and add entries.
create policy "staff_read_material_entries"
on public.material_entries for select
to authenticated
using (true);

create policy "staff_insert_material_entries"
on public.material_entries for insert
to authenticated
with check (true);

-- Private bucket for vendor bills.
insert into storage.buckets (id, name, public)
values ('bills', 'bills', false)
on conflict (id) do nothing;

create policy "staff_read_bills"
on storage.objects for select
to authenticated
using (bucket_id = 'bills');

create policy "staff_upload_bills"
on storage.objects for insert
to authenticated
with check (bucket_id = 'bills');
